/* Registers a feed changes; saved and restored around it */
static const uint8_t feed_touched[] = {
    0x01, 0x02, 0x04, 0x05, 0x1C, 0x1D, 0x2C, 0x2D, 0x3B,
    0x3D, 0x3E, 0x3F, 0x7D, 0x7E, 0x7F, 0x80, 0x81,
    0x82, 0x83, 0x84, 0x85, 0x86, 0x87,
    0x8A, 0x8B, 0x8C, 0x8D, 0x8E, 0x8F, 0x90, 0x91, 0x92,
    0xA4, 0xA5, 0xA6, 0xA7, 0xA8, 0xA9, 0xAA, 0xAB, 0xAE, 0xAF,
};

static double
now_s(void)
{
    struct timeval tv;
    gettimeofday(&tv, NULL);
    return tv.tv_sec + tv.tv_usec / 1e6;
}

SANE_Status
plustek8200i_feed_save(int fd, plustek8200i_feed_saved_t *saved)
{
    size_t i;
    for (i = 0; i < sizeof(feed_touched); i++) {
        SANE_Status st = plustek8200i_read_reg(fd, feed_touched[i], &saved->val[i]);
        if (st != SANE_STATUS_GOOD)
            return st;
    }
    saved->n = (int)sizeof(feed_touched);
    return SANE_STATUS_GOOD;
}

SANE_Status
plustek8200i_feed_restore(int fd, const plustek8200i_feed_saved_t *saved)
{
    uint8_t pairs[2 * sizeof(feed_touched)];
    int i;
    for (i = 0; i < saved->n; i++) {
        pairs[2 * i] = feed_touched[i];
        pairs[2 * i + 1] = saved->val[i];
    }
    return plustek8200i_write_regs(fd, pairs, 2 * saved->n);
}

SANE_Status
plustek8200i_feed(int fd, int steps, int slow_ramp)
{
    /* The captured feed block, FEEDL patched in */
    uint8_t regs[] = {
        0x3B, 0x01, 0x01, 0x22, 0x04, 0x42, 0x05, 0x48,
        0x3D, 0x00, 0x3E, 0x00, 0x3F, 0x00,
        0xA6, 0x00, 0xA7, 0x00, 0xA8, 0x00, 0xA9, 0x00,
        0x7D, 0x00, 0x7E, 0x36, 0x7F, 0xB0, 0x80, 0x00, 0x81, 0x40,
        0x82, 0x00, 0x83, 0x00, 0x84, 0xF2, 0x85, 0x00, 0x86, 0x29, 0x87, 0x72,
        0x2C, 0x00, 0x2D, 0x64, 0x1D, 0x80, 0x1C, 0x20,
        0xA4, 0x00, 0xA5, 0x02, 0xAA, 0x00, 0xAB, 0x02,
        0x8A, 0x00, 0x8B, 0x00, 0x8C, 0x00, 0x8D, 0x00, 0x8E, 0x00,
        0x8F, 0x00, 0x90, 0x00, 0x91, 0x00, 0x92, 0x00,
        0x02, 0x18, 0xAE, 0x00, 0xAF, 0x7F,
    };
    const uint8_t *ramp = slow_ramp ? feed_ramp_slow : feed_ramp_fast;
    SANE_Status st;
    uint8_t s = 0;
    int moving = 0;
    double t0, deadline;

    if (steps < 1 || steps > PLUSTEK8200I_FEED_MAX) {
        DBG(DBG_error, "feed: refusing %d steps (1..%d)\n", steps, PLUSTEK8200I_FEED_MAX);
        return SANE_STATUS_INVAL;
    }
    regs[11] = (steps >> 8) & 0xFF;
    regs[9] = (steps >> 16) & 0x0F;
    regs[13] = steps & 0xFF;
    if (!slow_ramp)
        regs[sizeof(regs) - 1] = 0xFF;   /* second feed: 0xAF = 0xFF */

    st = plustek8200i_write_regs(fd, regs, sizeof(regs));
    if (st == SANE_STATUS_GOOD)
        st = plustek8200i_dma_write(fd, 0x1000C000, ramp, 512);
    if (st == SANE_STATUS_GOOD)
        st = plustek8200i_dma_write(fd, 0x10010000, ramp, 512);
    if (st != SANE_STATUS_GOOD) {
        DBG(DBG_error, "feed: setup failed: %s\n", sane_strstatus(st));
        return st;
    }

    t0 = now_s();
    deadline = t0 + 15.0;
    st = plustek8200i_write_reg(fd, 0x0F, 0x01);
    if (st != SANE_STATUS_GOOD)
        return st;

    /* FEEDFSH is still set from the previous move: first see the feed
     * running (motor on or FEEDFSH clear), then wait for FEEDFSH with the
     * motor off. */
    while (now_s() < deadline) {
        st = plustek8200i_read_reg(fd, 0x101, &s);
        if (st != SANE_STATUS_GOOD)
            return st;
        if (!moving) {
            if ((s & 0x01) || !(s & 0x20))
                moving = 1;
        } else if ((s & 0x20) && !(s & 0x01)) {
            break;
        }
        usleep(2000);
    }
    if (now_s() >= deadline) {
        DBG(DBG_warning, "feed: %d steps not finished after 15 s (status 0x%02x)\n", steps, s);
        plustek8200i_write_reg(fd, 0x02, 0x00);
        return SANE_STATUS_IO_ERROR;
    }
    {
        static const uint8_t after[] = { 0x02, 0x08, 0x3D, 0x00, 0x3E, 0x00, 0x3F, 0x01 };
        plustek8200i_write_regs(fd, after, sizeof(after));
    }
    DBG(DBG_info, "feed: %d steps (%s ramp) in %.2f s, status 0x%02x\n",
        steps, slow_ramp ? "slow" : "fast", now_s() - t0, s);
    return SANE_STATUS_GOOD;
}
